defmodule ForemanServer.Coordinator.SetupProposal do
  @moduledoc """
  The first-turn setup proposal: a plain-text rendering of a project's setup
  recommendations (`ForemanServer.Projects.Recommendations`) that
  `Coordinator.SetupProposer` posts into the coordinator conversation as one
  `setup_proposal` system message.

  It is NOT generated by a model: no spend, and it works without a provider.
  `format/2` is pure and deterministic (the same recommendations give the same
  bytes; no timestamps):

    * the items are listed most important first (`action` > `warn` > `info`,
      otherwise in the order given), numbered, each with its stable id, severity,
      title and detail (one line, whitespace collapsed, detail clipped);
    * an item whose fix is a Foreman command (`Recommendations.applicable?/1`)
      offers `Reply "apply N"`; the coordinator turns that reply into an
      `apply_recommendation` action carrying only the id;
    * at most 10 items and 3,000 bytes: what does not fit is counted in a
      visible `[+N more: foreman project recommend <project>]` marker;
    * the text passes the run-log redactor, so nothing secret-looking survives
      even if a detector's wording ever quotes a value;
    * no recommendations is a single line saying so.

  `request?/1` recognises the `/setup` chat command, the operator's way to ask
  for a fresh proposal.
  """

  alias ForemanServer.Coordinator.Authority
  alias ForemanServer.Overwatch.WorkerLogPolicy
  alias ForemanServer.Projects.Recommendations
  alias ForemanServer.Projects.Recommendations.Recommendation

  @max_items 10
  @max_bytes 3_000
  @max_title 120
  @max_detail 300
  @command "/setup"
  @ready "Project looks ready: no setup recommendations."
  @greeting "Foreman checked how this project is set up. Most important first:"
  @rank %{action: 0, warn: 1, info: 2}

  @doc "Most items one proposal lists."
  @spec max_items() :: pos_integer()
  def max_items, do: @max_items

  @doc "Most bytes one proposal may take."
  @spec max_bytes() :: pos_integer()
  def max_bytes, do: @max_bytes

  @doc "The chat command that asks for a fresh proposal."
  @spec command() :: String.t()
  def command, do: @command

  @doc """
  True when `message` is the `/setup` command: authored by the operator through
  a trusted source (`Coordinator.Authority`) with exactly that text. Such a
  message is answered by the proposer, never by a coordinator turn.
  """
  @spec request?(map()) :: boolean()
  def request?(%{role: "operator", text: text} = message) when is_binary(text),
    do: String.trim(text) == @command and Authority.operator_authored?(message)

  def request?(_message), do: false

  @doc "Render `recommendations` of `project_id` as the proposal text."
  @spec format(String.t(), [Recommendation.t()]) :: String.t()
  def format(project_id, recommendations)
      when is_binary(project_id) and is_list(recommendations) do
    case Enum.sort_by(recommendations, &Map.fetch!(@rank, &1.severity)) do
      [] -> @ready
      sorted -> fit(project_id, Enum.take(sorted, @max_items), length(sorted))
    end
  end

  # Drops listed items from the end until the text fits. One item always fits: its
  # parts are clipped, and the greeting, footer and marker are short constants plus
  # the project id twice.
  defp fit(project_id, shown, total) do
    Enum.find_value(length(shown)..1//-1, fn count ->
      text = render(project_id, Enum.take(shown, count), total)
      if byte_size(text) <= @max_bytes, do: text
    end) || render(project_id, Enum.take(shown, 1), total)
  end

  defp render(project_id, items, total) do
    body = items |> Enum.with_index(1) |> Enum.map_join("\n", &item/1)

    more =
      case total - length(items) do
        0 -> ""
        n -> "\n[+#{n} more: foreman project recommend #{project_id}]"
      end

    footer =
      "Reply \"apply N\" to apply an item that offers a fix, send #{@command} for a fresh list, " <>
        "or run `foreman project recommend #{project_id}` for details."

    WorkerLogPolicy.redact(@greeting <> "\n\n" <> body <> more <> "\n\n" <> footer)
  end

  defp item({%Recommendation{} = rec, number}) do
    line =
      "#{number}. [#{rec.severity}] #{rec.id} - #{clean(rec.title, @max_title)}: " <>
        clean(rec.detail, @max_detail)

    if Recommendations.applicable?(rec),
      do:
        line <> "\n   Reply \"apply #{number}\" to have Foreman run this fix (#{rec.fix.type}).",
      else: line
  end

  defp clean(text, max) do
    flat = text |> String.replace(~r/\s+/, " ") |> String.trim()
    if String.length(flat) > max, do: String.slice(flat, 0, max - 1) <> "…", else: flat
  end
end
